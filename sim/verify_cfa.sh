pass() { echo "PASS: $1"; }
fail() { echo "FAIL: $1"; exit 1; }

# ---------------------------------------------------------------------------
# 1. aes_gf4_mul
# ---------------------------------------------------------------------------
cat > "$OUTDIR/tb_gf4_mul.cpp" << 'EOF'
#include "Vaes_gf4_mul.h"
#include "verilated.h"
#include <cstdio>

// Test field axioms directly on the RTL — no external reference needed.
// Identity element in Canright normal basis is 0xF.
static uint8_t mul(Vaes_gf4_mul* dut, uint8_t a, uint8_t b) {
    dut->a = a; dut->b = b; dut->eval(); return dut->p;
}

int main(int argc, char** argv) {
    VerilatedContext* ctx = new VerilatedContext;
    ctx->commandArgs(argc, argv);
    Vaes_gf4_mul* dut = new Vaes_gf4_mul(ctx);
    int errors = 0;
    const uint8_t ONE = 0xF; // multiplicative identity

    for (int a = 0; a < 16; a++) {
        // a * 0 == 0
        if (mul(dut,a,0) != 0) {
            printf("  FAIL: 0x%x * 0 = 0x%x (expect 0)\n", a, mul(dut,a,0));
            errors++;
        }
        // a * identity == a
        if (mul(dut,a,ONE) != a) {
            printf("  FAIL: 0x%x * ONE = 0x%x (expect 0x%x)\n", a, mul(dut,a,ONE), a);
            errors++;
        }
        // commutativity: a*b == b*a
        for (int b = 0; b < 16; b++) {
            if (mul(dut,a,b) != mul(dut,b,a)) {
                printf("  FAIL: 0x%x*0x%x=0x%x != 0x%x*0x%x=0x%x\n",
                       a,b,mul(dut,a,b), b,a,mul(dut,b,a));
                errors++;
            }
        }
        // distributivity: a*(b^c) == a*b ^ a*c
        for (int b = 0; b < 16; b++) for (int c = 0; c < 16; c++) {
            uint8_t lhs = mul(dut,a,b^c);
            uint8_t rhs = mul(dut,a,b) ^ mul(dut,a,c);
            if (lhs != rhs) {
                printf("  FAIL distributivity: 0x%x*(0x%x^0x%x)\n", a, b, c);
                errors++;
            }
        }
    }
    if (!errors) printf("PASS: aes_gf4_mul — field axioms hold for all inputs\n");
    else printf("FAIL: aes_gf4_mul — %d axiom violations\n", errors);
    dut->final(); delete dut; delete ctx;
    return errors ? 1 : 0;
}
EOF

verilator --cc --build -Mdir "$OUTDIR/vl_gf4_mul" \
  "$BASEDIR/rtl/aes_gf4_mul.sv" --top-module aes_gf4_mul 2>/dev/null
g++ -std=c++17 -I"$OUTDIR/vl_gf4_mul" -I"$VLR/include" \
    "$OUTDIR/tb_gf4_mul.cpp" "$OUTDIR/vl_gf4_mul/Vaes_gf4_mul__ALL.a" \
