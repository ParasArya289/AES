#!/bin/bash
# Verify all CFA S-Box RTL modules against FIPS-197 reference.
# Run from the aes/ directory: bash sim/verify_cfa.sh

set -e
BASEDIR=$(dirname "$(realpath "$0")")/..
VLR=$(verilator --getenv VERILATOR_ROOT)
OUTDIR=/tmp/cfa_verify
