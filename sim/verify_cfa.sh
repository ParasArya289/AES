#include "Vaes_gf4_mul.h"
#include "verilated.h"
#include <cstdio>
// Use the RTL multiplier itself to verify inv: a * inv(a) must equal identity (0xF).
int main(int argc, char** argv) {
    VerilatedContext* ctx = new VerilatedContext;
    ctx->commandArgs(argc, argv);
    Vaes_gf4_inv* inv_dut = new Vaes_gf4_inv(ctx);
    Vaes_gf4_mul* mul_dut = new Vaes_gf4_mul(ctx);
    int errors = 0;
    for (int a = 1; a < 16; a++) {
        inv_dut->a = a; inv_dut->eval();
        mul_dut->a = a; mul_dut->b = inv_dut->a_inv; mul_dut->eval();
        if (mul_dut->p != 0xF) {
            printf("  FAIL: gf4_inv(0x%x)=0x%x, a*inv(a)=0x%x (expect 0xF)\n",
                   a, (int)inv_dut->a_inv, (int)mul_dut->p);
            errors++;
        }
    }
    if (!errors) printf("PASS: aes_gf4_inv — all 15 non-zero inverses correct (a*inv(a)==0xF)\n");
    else printf("FAIL: aes_gf4_inv — %d errors\n", errors);
    inv_dut->final(); mul_dut->final();
    delete inv_dut; delete mul_dut; delete ctx;
    return errors ? 1 : 0;
}
EOF

verilator --cc --build -Mdir "$OUTDIR/vl_gf4_inv" \
